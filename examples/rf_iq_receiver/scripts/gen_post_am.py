#!/usr/bin/env python3
"""Build spice/post_am.lib: the pre-layout AM-chain module netlists plus the
Magic PEX node capacitances.

Methodology (the hybrid PEX established with RX_TIA): the KLayout LVS deck
proves the layout implements exactly the schematic devices (TR10_LVS PASS
against the strict contracts), the Magic PEX node capacitances are geometric
and valid, but Magic's device connectivity extraction is streamout-only.  So
the post-view module = pre-layout device netlist + extracted caps attached to
the labelled (LVS-verified) nets.

    python3 scripts/gen_post_am.py

Reads  layout/pex/rx_<mod>.spice and spice/{lna,mixer_tia,demod_am}.lib
Writes spice/post_am.lib  (defines RX_LNA, RX_MIXER, RX_TIA, RX_AM_DEMOD)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.abspath(os.path.join(HERE, ".."))
SPICE = os.path.join(PKG, "spice")
PEX = os.path.join(PKG, "layout", "pex")

# module -> (lib file, subckt, layout net names that carry PEX caps)
MODULES = [
    ("lna.lib", "RX_LNA", ["d", "g", "out", "vdd", "vss"]),
    ("mixer_tia.lib", "RX_MIXER",
     ["out_i", "out_q", "lo0", "lo90", "lo180", "lo270", "rf_p", "rf_n", "vss"]),
    ("mixer_tia.lib", "RX_TIA", ["out", "in", "vss"]),
    ("demod_am.lib", "RX_AM_DEMOD",
     ["ii", "qq", "bi", "bq", "d1", "d2", "d3", "d4",
      "tail", "tailq", "out", "vdd", "vss"]),
]

# the free-running VCO is checked on its own (it is not in the AM chain,
# which drives the mixer from ideal 4-phase LO sources)
VCO_MODULES = [
    ("vco.lib", "RX_VCO", ["out_p", "out_n", "vtune", "tail", "vss"]),
]
# the TIA layout labels are upper case
CASE_MAP = {"RX_TIA": {"OUT": "out", "IN": "in", "VSS": "vss"}}

CAP_RE = re.compile(r"^C\d+\s+(\S+)\s+(\S+)\s+(\S+)\s*$")


def block(lib_path: str, subckt: str) -> str:
    """Return the .subckt ... .ends text of one subckt from a lib file."""
    lines = open(lib_path).read().splitlines()
    out, on = [], False
    for ln in lines:
        if ln.strip().startswith(".subckt") and ln.split()[1] == subckt:
            on = True
        if on:
            out.append(ln)
            if ln.strip().startswith(".ends"):
                break
    if not out:
        raise SystemExit(f"{subckt} not found in {lib_path}")
    return "\n".join(out)


def pex_caps(mod_key: str, nets) -> list:
    """Extract the PEX caps attached to labelled nets of one module."""
    path = os.path.join(PEX, "rx_%s.spice" % mod_key)
    low = {n.lower() for n in nets}
    cmap = CASE_MAP.get(mod_key, {})
    caps = []
    for ln in open(path):
        f = ln.split()
        if len(f) < 4 or not re.match(r"^C\d+$", f[0]):
            continue
        n1, n2, val = f[1], f[2], f[3]
        n1 = cmap.get(n1, n1).lower()
        n2 = cmap.get(n2, n2).lower()
        if n1 not in low:
            continue                      # dangling extraction node: dropped
        if n2 == "0":
            caps.append((n1, "0", val))   # substrate cap
        elif n2 in low:
            caps.append((n1, n2, val))    # coupling cap
    return caps


def main() -> int:
    rc = emit(MODULES, "post_am.lib", "Post-layout AM-chain modules (hybrid PEX).")
    rc |= emit(VCO_MODULES, "post_vco.lib", "Post-layout VCO (hybrid PEX).")
    return rc


def emit(mods, out_name, title) -> int:
    out = ["* " + title,
           "* Pre-layout device netlists + Magic PEX node capacitances on the",
           "* LVS-verified nets; generated by scripts/gen_post_am.py -- do not edit.",
           ""]
    for lib, subckt, nets in mods:
        mod_key = subckt.replace("RX_", "").lower()
        mod_key = {"am_demod": "amdemod"}.get(mod_key, mod_key)
        caps = pex_caps(mod_key, nets)
        txt = block(os.path.join(SPICE, lib), subckt)
        lines = txt.splitlines()
        ends = lines[-1]
        body = lines[:-1]
        out.extend(body)
        out.append("* ---- Magic PEX parasitics (layout/pex/rx_%s.spice) ----" % mod_key)
        for i, (n1, n2, val) in enumerate(caps):
            out.append("Cpex%d %s %s %s" % (i, n1, n2, val))
        out.append(ends)
        out.append("")
        tot = sum(float(c[2].replace("f", "e-15").replace("p", "e-12"))
                  for c in caps if c[1] == "0")
        print(f"{subckt}: {len(caps)} caps attached "
              f"(substrate total {tot*1e15:.1f} fF)")
    path = os.path.join(SPICE, out_name)
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
