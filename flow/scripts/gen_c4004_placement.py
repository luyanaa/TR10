#!/usr/bin/env python3
"""Generate the C4004 reproduction placement data from the upstream DEF.

The C4004 core is reproduced from ``jun1okamura/TR-1um_C4004`` (Apache-2.0):

* ``openroad/c4004_core_syn.v``      gate-level netlist (638 instances)
* ``openroad/c4004_core_placed.def`` upstream hand placement (11 rows)

The upstream floorplan cannot be expressed by ``initialize_floorplan``:
its rows sit at ``y = 27 + 145.8 * r`` (11 rows of 340 sites) because the
59.4 um compact cells need a 145.8 um pitch to keep the well/active
spacing rules.  The rows and the component coordinates are therefore
emitted as Tcl data for ``examples/c4004_cmp/manual_place.tcl``.

Two files are produced:

``placements.tcl``
    ``C4004_ROWS`` / ``C4004_PLACE`` Tcl lists used by manual_place.tcl.

``src/c4004_pins.def``
    A pin-only DEF (DIEAREA + PINS) used as ``FP_DEF_TEMPLATE``.

All 811 upstream components are emitted, including the 129 ``FILL3`` /
``FILL2`` cells.  The fillers are part of the upstream physical intent:
consecutive logic cells are 16.2 um apart in places, which leaves two
N-well islands 3.6 um apart and violates ``WN.S1``/``WN.S7``; the filler
merges them exactly as the upstream layout does.  The flow therefore
places them itself and still keeps ``RUN_FILL_INSERTION`` off.

Usage:
    flow/scripts/gen_c4004_placement.py \
        --def /tmp/opencode/TR-1um_C4004/openroad/c4004_core_placed.def \
        --netlist /tmp/opencode/TR-1um_C4004/openroad/c4004_core_syn.v \
        --out-dir examples/c4004_cmp
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# Upstream uses FILL3/FILL2 only; FILL1 is never instanced.
FILL_MASTERS = {"FILL1", "FILL2", "FILL3"}

ROW_RE = re.compile(
    r"^ROW\s+(\S+)\s+(\S+)\s+(-?\d+)\s+(-?\d+)\s+(\S+)\s+DO\s+(\d+)\s+BY\s+1\s+STEP\s+(\d+)\s+(-?\d+)\s*;",
    re.M,
)
COMP_RE = re.compile(
    r"^\s*-\s+(\S+)\s+(\S+)\s+\+\s+(\S+)\s+\(\s*(-?\d+)\s+(-?\d+)\s*\)\s+(\S+)\s*;",
    re.M,
)
PINS_RE = re.compile(r"^(PINS\s+\d+\s*;.*?^END PINS)", re.M | re.S)
DIE_RE = re.compile(r"^DIEAREA.*;$", re.M)

LAYER_RENAME = {"METAL1": "M1", "METAL2": "M2", "VIA1": "V1"}

ORIENT = {"N": "R0", "S": "R180", "E": "R270", "W": "R90",
          "FN": "MY", "FS": "MX", "FE": "MYR90", "FW": "MXR90"}


def parse_netlist_instances(path: Path) -> set[str]:
    # Instances look like:  MASTER inst_name ( .PIN(net) ... ) ;
    text = path.read_text()
    return {m[1] for m in re.findall(r"^\s{2}(\w+)\s+(\w+)\s*\(", text, re.M)}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--def", dest="def_path", required=True, type=Path)
    ap.add_argument("--netlist", required=True, type=Path)
    ap.add_argument("--out-dir", required=True, type=Path)
    args = ap.parse_args()

    def_text = args.def_path.read_text()

    rows = []
    for m in ROW_RE.finditer(def_text):
        _, site, x0, y, orient, count, step, _ = m.groups()
        if site != "TR1UM":
            sys.exit(f"unexpected site {site}")
        if orient != "N":
            sys.exit(f"unexpected row orientation {orient}")
        if int(x0) != 0 or int(step) != 5400:
            sys.exit("unexpected row origin/step")
        rows.append((int(y), int(count)))

    comp_text = re.search(r"COMPONENTS \d+ ;(.*?)END COMPONENTS", def_text, re.S).group(1)
    comps = []
    for m in COMP_RE.finditer(comp_text):
        name, master, status, x, y, orient = m.groups()
        comps.append((name, master, int(x), int(y), ORIENT[orient]))

    net_insts = parse_netlist_instances(args.netlist)
    def_std = {c[0] for c in comps if c[1] not in {"SRAM128", "TAP2"} | FILL_MASTERS}
    missing_in_netlist = sorted(def_std - net_insts)
    if missing_in_netlist:
        sys.exit(f"{len(missing_in_netlist)} DEF cells missing from netlist: {missing_in_netlist[:8]}")
    if "u_sram" not in net_insts:
        sys.exit("netlist has no u_sram instance")

    out = args.out_dir
    (out / "src").mkdir(parents=True, exist_ok=True)

    lines = [
        "# Generated by flow/scripts/gen_c4004_placement.py -- do not edit.",
        "# Source: jun1okamura/TR-1um_C4004 openroad/c4004_core_placed.def (Apache-2.0).",
        f"# rows: {len(rows)}, placed objects: {len(comps)} "
        f"({sum(1 for c in comps if c[1] not in ('SRAM128', 'TAP2') and c[1] not in FILL_MASTERS)} stdcells + "
        f"{sum(1 for c in comps if c[1] in FILL_MASTERS)} fillers + "
        f"{sum(1 for c in comps if c[1] == 'TAP2')} TAP2 + SRAM128)",
        "",
        "set C4004_ROWS {",
    ]
    for y, count in rows:
        lines.append(f"    {{{y} {count}}}")
    lines.append("}")
    lines.append("")
    lines.append("# {name master x y orient}")
    lines.append("set C4004_PLACE {")
    for name, master, x, y, orient in comps:
        lines.append(f"    {{{name} {master} {x} {y} {orient}}}")
    lines.append("}")
    (out / "placements.tcl").write_text("\n".join(lines) + "\n")

    # Pin-only DEF template: DIEAREA + PINS, layers renamed to the PDK names.
    pins = PINS_RE.search(def_text)
    die = DIE_RE.search(def_text)
    if pins is None or die is None:
        sys.exit("DEF has no PINS/DIEAREA section")
    pin_text = pins.group(1)
    for old, new in LAYER_RENAME.items():
        pin_text = re.sub(rf"\b{old}\b", new, pin_text)
    template = "\n".join([
        "VERSION 5.8 ;",
        'DIVIDERCHAR "/" ;',
        'BUSBITCHARS "[]" ;',
        "DESIGN c4004_core ;",
        "UNITS DISTANCE MICRONS 1000 ;",
        "",
        die.group(0),
        "",
        pin_text,
        "",
        "END DESIGN",
        "",
    ])
    (out / "src/c4004_pins.def").write_text(template)

    print(f"rows={len(rows)} placed={len(comps)} "
          f"({sum(1 for c in comps if c[1] not in ('SRAM128', 'TAP2') and c[1] not in FILL_MASTERS)} std, "
          f"{sum(1 for c in comps if c[1] in FILL_MASTERS)} fill)")
    print(f"wrote {out/'placements.tcl'} and {out/'src/c4004_pins.def'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
