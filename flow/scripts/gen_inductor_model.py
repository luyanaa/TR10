#!/usr/bin/env python3
"""Generate a TR10 spiral-inductor SPICE subckt from geometry.

The PDK has no spiral inductor.  This script turns the same square-spiral
description that the KLayout PCell draws into the pi-model parameters used by
models_IP62_inductor.lib:

    L      Wheeler (square spiral)
    Rdc    M2 sheet resistance * centreline length / width, plus the M1
           underpass and the via cuts
    Cox    M2-to-substrate capacitance from the stackup, per pi-model side
    Rsub   engineering substrate resistance
    Csub   engineering substrate capacitance

The geometry comes from
libs.tech/klayout/tech/python/cells/inductor_geom.py -- the module the PCell
also uses -- so the SPICE numbers and the drawn cell describe the same
inductor.  `--format json` prints d_in, length and area for cross-checking
against the layout.

ENGINEERING ONLY.  The stackup is a placeholder (see
libs.tech/parasitics/README.md), so Q is not qualified.  Replace L/R/C with
FastHenry or measured data before sign-off.

Usage:
    python3 gen_inductor_model.py --turns 4 --d-out 250 --width 8 \
        --spacing 3 --name IND_4T_250U

    python3 gen_inductor_model.py ... --format json
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import math
import os
import sys

PDK = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
GEOM_PATH = os.path.join(PDK, "libs.tech/klayout/tech/python/cells",
                         "inductor_geom.py")


def _load_geometry():
    """Load inductor_geom.py without importing the pya-dependent package."""
    spec = importlib.util.spec_from_file_location("inductor_geom", GEOM_PATH)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


geom = _load_geometry()

EPS0 = 8.8541878128e-12       # F/m
IMD_EPS_R = 4.0
M2_TO_SUB_UM = 0.645          # M2 Zmin 100.845 - substrate top 100.200


def model(turns: int, d_out: float, width: float, spacing: float,
          rsub: float, csub_pf: float, pad: float,
          metal: str = "al") -> dict:
    g = geom.geometry(turns, d_out, width, spacing, pad=pad, metal=metal)
    l_nh = geom.wheeler_nh(turns, d_out, width, spacing)

    # M2 area: winding + both pads + the outer stub.
    area_m2 = g["length_m2_um"] * width
    if g["pad_p"] is not None:
        for box in (g["pad_p"], g["pad_n"], g["stub_p"]):
            area_m2 += (box[2] - box[0]) * (box[3] - box[1])
    # The M1 underpass sits under the winding, so its overlap with M2 is
    # small; fold it in at the same density for a first-order estimate.
    area_m1 = g["length_m1_um"] * geom.TRACE_WMIN

    c_total_f = (EPS0 * IMD_EPS_R / (M2_TO_SUB_UM * 1e-6)
                 * (area_m2 + area_m1) * 1e-12)
    return {
        "turns": turns,
        "d_out_um": d_out,
        "d_in_um": g["d_in_um"],
        "d_avg_um": g["d_avg_um"],
        "rho": g["rho"],
        "width_um": width,
        "spacing_um": spacing,
        "length_m2_um": g["length_m2_um"],
        "length_m1_um": g["length_m1_um"],
        "area_m2_um2": area_m2,
        "l_nh": l_nh,
        "metal": metal,
        "rsh_m2_ohm_sq": g["rsh_m2_ohm_sq"],
        "rsh_m1_ohm_sq": g["rsh_m1_ohm_sq"],
        "r_dc_ohm": g["r_dc_ohm"],
        "r_dc_metal_ohm": g["r_dc_metal_ohm"],
        "n_via": g["n_via"],
        "c_ox_pf": 0.5 * c_total_f * 1e12,   # per pi-model side
        "c_ox_total_pf": c_total_f * 1e12,
        "r_sub_ohm": rsub,
        "c_sub_pf": csub_pf,
        "q_metal_1ghz": (2 * math.pi * 1e9 * l_nh * 1e-9
                         / g["r_dc_ohm"]) if g["r_dc_ohm"] else 0.0,
    }


def spice_subckt(name: str, m: dict) -> str:
    return f"""* TR10 spiral inductor {name} -- generated by gen_inductor_model.py
* turns={m['turns']} d_out={m['d_out_um']}um w={m['width_um']}um s={m['spacing_um']}um
* d_in={m['d_in_um']:.2f}um d_avg={m['d_avg_um']:.2f}um rho={m['rho']:.4f}
* len_M2={m['length_m2_um']:.1f}um len_M1={m['length_m1_um']:.1f}um area={m['area_m2_um2']:.1f}um^2
* metal={m['metal']} Rsh_M2={m['rsh_m2_ohm_sq']:.4f} Rsh_M1={m['rsh_m1_ohm_sq']:.4f} ohm/sq
* c_ox is PER SIDE (half of the {m['c_ox_total_pf']:.3f}pF total)
* ENGINEERING ESTIMATE -- stackup not qualified, not for sign-off.
.subckt {name} p n sub
.param l_nh={m['l_nh']:.6g} r_dc={m['r_dc_ohm']:.6g}
.param c_ox={m['c_ox_pf']:.6g}p r_sub={m['r_sub_ohm']:.6g} c_sub={m['c_sub_pf']:.6g}p
XL1 p n sub IND_PI l_nh=l_nh r_dc=r_dc c_ox=c_ox r_sub=r_sub c_sub=c_sub
.ends {name}
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--turns", type=int, default=4)
    ap.add_argument("--d-out", type=float, default=250.0, help="outer size, um")
    ap.add_argument("--width", type=float, default=8.0, help="M2 width, um")
    ap.add_argument("--spacing", type=float, default=3.0, help="M2 spacing, um")
    ap.add_argument("--pad", type=float, default=20.0, help="terminal pad, um")
    ap.add_argument("--name", default=None)
    ap.add_argument("--metal", choices=tuple(geom.METALS), default=geom.DEFAULT_METAL,
                    help="conductor preset (al = thin-film aluminium, cu = 58 MS/m)")
    ap.add_argument("--rsub", type=float, default=500.0, help="substrate R, ohm")
    ap.add_argument("--csub", type=float, default=0.05, help="substrate C, pF")
    ap.add_argument("--format", choices=("spice", "json"), default="spice")
    args = ap.parse_args(argv)

    try:
        m = model(args.turns, args.d_out, args.width, args.spacing,
                  args.rsub, args.csub, args.pad, args.metal)
    except ValueError as exc:
        ap.error(str(exc))

    name = args.name or f"IND_{args.turns}T_{int(round(args.d_out))}U"
    if args.format == "json":
        print(json.dumps(m, indent=2))
    else:
        print(spice_subckt(name, m))
    return 0


if __name__ == "__main__":
    sys.exit(main())
