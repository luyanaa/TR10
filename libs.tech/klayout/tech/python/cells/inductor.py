"""Square-spiral inductor PCell (M2 spiral + M1 underpass).

There is no inductor in the baseline PDK.  This cell draws a two-terminal
square spiral using only the qualified drawing layers:

    M2   spiral winding and both terminal pads
    M1   underpass from the centre out to the second terminal
    V1   1.4 x 1.4 via at the centre and at the underpass exit

Design rules enforced here (libs.tech/klayout/tech/python/cells/rules_def.py):

    M2.W1 = 3.0   M2.S1 = 2.0
    M1.W1 = 1.8   M1.S1 = 1.4
    V1.W1 = 1.4 fixed, V1.M1 = 1.0, M2.V1 = 1.0
    all layers on a 0.05 um grid, 90-degree edges only

Because a V1 needs 1.0 um of M2 on every side, the winding cannot be
narrower than 3.4 um; `width` is coerced up to that.

The electrical model is generated by flow/scripts/gen_inductor_model.py
from the same geometry module, so the SPICE subckt and the drawn cell
describe the same inductor.

ENGINEERING ONLY -- the stackup in libs.tech/parasitics/TR10_stackup.xml is a
placeholder, so Q from this cell is not silicon-qualified.
"""
import pya

from .layers_def import *
from .rules_def import *
from .inductor_geom import (GRID, TRACE_WMIN, M2_SMIN, V1_SIZE, geometry)


class inductor_spiral(pya.PCellDeclarationHelper):

    def __init__(self):
        super(inductor_spiral, self).__init__()
        self.param("turns",   self.TypeInt,    "Turns",        default=4)
        self.param("d_out",   self.TypeDouble, "Outer size(um)", default=250.0)
        self.param("width",   self.TypeDouble, "M2 width(um)", default=8.0)
        self.param("spacing", self.TypeDouble, "M2 spacing(um)", default=3.0)
        self.param("pad",     self.TypeDouble, "Pad size(um)", default=20.0)
        self.param("pad_gap", self.TypeDouble, "Pad gap(um)",  default=10.0)
        self._err = ""

    def display_text_impl(self):
        return ("inductor_spiral(N:%d,D:%.1f,W:%.1f,S:%.1f)"
                % (self.turns, self.d_out, self.width, self.spacing))

    def coerce_parameters_impl(self):
        self._err = ""
        # Snap to the 0.05 um grid first, then clamp to the DRC minimums.
        self.d_out = round(round(self.d_out / GRID) * GRID, 6)
        self.width = round(round(self.width / GRID) * GRID, 6)
        self.spacing = round(round(self.spacing / GRID) * GRID, 6)
        self.pad = round(round(self.pad / GRID) * GRID, 6)
        self.pad_gap = round(round(self.pad_gap / GRID) * GRID, 6)

        if self.turns < 1:
            self.turns = 1
        if self.turns > 12:
            self.turns = 12
        if self.width < TRACE_WMIN:
            self.width = TRACE_WMIN
        if self.spacing < M2_SMIN:
            self.spacing = M2_SMIN
        if self.d_out < 20.0:
            self.d_out = 20.0
        if self.pad < 0.0:
            self.pad = 0.0
        if self.pad_gap < M2_SMIN:
            self.pad_gap = M2_SMIN
        # Keep at least one grid step of inner hole.
        min_dout = 2 * self.turns * (self.width + self.spacing) + self.width
        if self.d_out < min_dout:
            self.d_out = round(min_dout / GRID) * GRID

    def produce_impl(self):
        try:
            g = geometry(self.turns, self.d_out, self.width, self.spacing,
                         self.pad, self.pad_gap)
        except ValueError as exc:
            self._err = str(exc)
            return

        dbu = self.layout.dbu

        def rect(box):
            x0, y0, x1, y1 = box
            return pya.DBox(x0, y0, x1, y1).to_itype(dbu)

        # ---- M2 spiral: stroke the centreline polyline
        ipts = [pya.Point(int(round(x / dbu)), int(round(y / dbu)))
                for x, y in g["points"]]
        iw = int(round(g["width_um"] / dbu))
        self.cell.shapes(M2_layer).insert(pya.Path(ipts, iw))

        if g["pad_p"] is not None:
            self.cell.shapes(M2_layer).insert(rect(g["pad_p"]))
            self.cell.shapes(M2_layer).insert(rect(g["pad_n"]))
            self.cell.shapes(M2_layer).insert(rect(g["stub_p"]))

        # ---- M1 underpass
        if g["underpass"] is not None:
            self.cell.shapes(M1_layer).insert(rect(g["underpass"]))

        # ---- V1
        self.cell.shapes(V1_layer).insert(rect(g["via_inner"]))
        if g["via_outer"] is not None:
            self.cell.shapes(V1_layer).insert(rect(g["via_outer"]))
